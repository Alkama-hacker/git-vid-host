function gvh_make_token($cfg)
{
    $raw = time() . '.' . bin2hex(random_bytes(9));
    return $raw . '.' . hash_hmac('sha256', $raw, $cfg['master']);
}

function gvh_parse_token($cfg, $token, &$raw)
{
    $parts = explode('.', (string) $token);
    if (count($parts) !== 3) {
        return false;
    }
    $raw = $parts[0] . '.' . $parts[1];
    if (!hash_equals(hash_hmac('sha256', $raw, $cfg['master']), $parts[2])) {
        return false;
    }
    $ts = (int) $parts[0];
    if ($ts < 1 || abs(time() - $ts) > 43200) {
        return false;
    }
    return true;
}

function gvh_request_token($cfg)
{
    if (isset($_GET[$cfg['pt']]) && is_string($_GET[$cfg['pt']])) {
        return $_GET[$cfg['pt']];
    }
    if (isset($_SERVER['HTTP_X_GVH_S']) && is_string($_SERVER['HTTP_X_GVH_S'])) {
        return $_SERVER['HTTP_X_GVH_S'];
    }
    if (isset($_COOKIE[$cfg['cookie']]) && is_string($_COOKIE[$cfg['cookie']])) {
        return $_COOKIE[$cfg['cookie']];
    }
    return '';
}

function gvh_set_cookie($cfg, $token)
{
    $c = $cfg['cookie'] . '=' . $token . '; Path=/; Max-Age=43200; HttpOnly; SameSite=Lax';
    if (gvh_is_https()) {
        $c .= '; Secure';
    }
    gvh_hdr('Set-Cookie', $c);
}

function gvh_session_key($cfg, $raw)
{
    return hash_hmac('sha256', 'k|' . $raw, $cfg['sign'], true);
}

