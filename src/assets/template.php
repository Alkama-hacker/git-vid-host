function gvh_send($body, $code)
{
    gvh_status($code);
    if (isset($_SERVER['REQUEST_METHOD']) && $_SERVER['REQUEST_METHOD'] === 'HEAD') {
        return;
    }
    $accept = isset($_SERVER['HTTP_ACCEPT_ENCODING']) ? $_SERVER['HTTP_ACCEPT_ENCODING'] : '';
    if (function_exists('gzencode') && strpos($accept, 'gzip') !== false && strlen($body) > 1024) {
        $gz = @gzencode($body, 6);
        if ($gz !== false) {
            gvh_hdr('Content-Encoding', 'gzip');
            gvh_hdr('Vary', 'Accept-Encoding');
            $body = $gz;
        }
    }
    gvh_hdr('Content-Length', (string) strlen($body));
    echo $body;
}

function gvh_page($html, $code)
