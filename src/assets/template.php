function gvh_cfg_decode($s)
{
    if (substr($s, 0, 3) === 'G1.') {
        $z = @base64_decode(substr($s, 3), true);
        if ($z !== false && function_exists('gzinflate')) {
            $j = @gzinflate($z);
            if ($j !== false) {
                $a = json_decode($j, true);
                if (is_array($a)) {
                    return $a;
                }
            }
        }
    }
    if (substr($s, 0, 3) === 'B1.') {
        $j = @base64_decode(substr($s, 3), true);
        $a = json_decode($j, true);
        if (is_array($a)) {
            return $a;
        }
    }
    return array();
}

function gvh_hdr($k, $v)
{
    $GLOBALS['GVH_HDR'][] = $k . ': ' . $v;
    if (!headers_sent()) {
        @header($k . ': ' . $v, true);
    }
}

function gvh_status($code)
{
    $GLOBALS['GVH_STATUS'] = $code;
    if (!headers_sent() && function_exists('http_response_code')) {
        @http_response_code($code);
    }
}

