function gvh_xor($data, $key)
{
    $out = '';
    $n = strlen($data);
    $m = count($key);
    for ($i = 0; $i < $n; $i++) {
        $out .= chr(ord($data[$i]) ^ $key[$i % $m]);
    }
    return $out;
}

function gvh_b64d($s)
{
    $b = @base64_decode($s, true);
    return $b === false ? '' : $b;
}

function gvh_is_https()
{
    if (!empty($_SERVER['HTTPS']) && strtolower($_SERVER['HTTPS']) !== 'off') {
        return true;
    }
    if (isset($_SERVER['HTTP_X_FORWARDED_PROTO']) && strtolower($_SERVER['HTTP_X_FORWARDED_PROTO']) === 'https') {
        return true;
    }
    if (isset($_SERVER['SERVER_PORT']) && (int) $_SERVER['SERVER_PORT'] === 443) {
        return true;
    }
    return false;
}

function gvh_host()
{
    $h = isset($_SERVER['HTTP_HOST']) ? strtolower($_SERVER['HTTP_HOST']) : '';
    $p = strpos($h, ':');
    if ($p !== false) {
        $h = substr($h, 0, $p);
    }
    return $h;
}

