function gvh_ctr_iv($iv, $block)
{
    $out = $iv;
    $carry = $block;
    for ($i = 15; $i >= 0 && $carry > 0; $i--) {
        $v = ord($out[$i]) + ($carry & 0xff);
        $carry = ($carry >> 8) + ($v >> 8);
        $out[$i] = chr($v & 0xff);
    }
    return $out;
}

function gvh_asset_bytes($cfg, $a, $start, $len)
{
    if (!empty($a['file'])) {
        $path = __DIR__ . '/' . $cfg['data_dir'] . '/' . $a['file'];
        $fh = @fopen($path, 'rb');
        if (!$fh) {
            return false;
        }
        $blockStart = $start - ($start % 16);
        $plain = '';
        $want = $len + ($start - $blockStart);
        @fseek($fh, $blockStart);
        $ct = $want > 0 ? @fread($fh, $want) : '';
        @fclose($fh);
        $iv = gvh_ctr_iv(gvh_b64d($a['iv']), (int) ($blockStart / 16));
        $dec = @openssl_decrypt($ct, 'aes-256-ctr', gvh_b64d($a['k']), OPENSSL_RAW_DATA, $iv);
        if ($dec === false) {
            return false;
        }
        return substr($dec, $start - $blockStart, $len);
    }
    $full = gvh_b64d($a['ct']);
    $blockStart = $start - ($start % 16);
    $want = $len + ($start - $blockStart);
    $slice = substr($full, $blockStart, $want);
    $iv = gvh_ctr_iv(gvh_b64d($a['iv']), (int) ($blockStart / 16));
    $dec = @openssl_decrypt($slice, 'aes-256-ctr', gvh_b64d($a['k']), OPENSSL_RAW_DATA, $iv);
    if ($dec === false) {
        return false;
    }
    return substr($dec, $start - $blockStart, $len);
}

function gvh_asset($cfg, $token)
{
    $id = (isset($_GET[$cfg['ap']]) && is_string($_GET[$cfg['ap']])) ? strtolower($_GET[$cfg['ap']]) : '';
    if (!preg_match('/^[a-f0-9]{12,80}$/', $id) || !isset($cfg['assets'][$id])) {
        gvh_status(404);
        exit;
    }
    $ok = false;
    $raw = '';
    if ($token !== '' && gvh_parse_token($cfg, $token, $raw)) {
        $ok = true;
    }
    if (!$ok && gvh_ref_ok($cfg)) {
        $ok = true;
    }
    if (isset($_SERVER['HTTP_SEC_FETCH_SITE']) && $_SERVER['HTTP_SEC_FETCH_SITE'] === 'cross-site') {
        $ok = false;
    } elseif (!$ok && gvh_host() !== '' && !empty($_SERVER['HTTP_SEC_FETCH_SITE'])
        && $_SERVER['HTTP_SEC_FETCH_SITE'] === 'same-origin') {
        $ok = true;
    }
    if (!$ok) {
        gvh_status(403);
        gvh_hdr('Content-Type', 'text/plain; charset=utf-8');
        echo 'sealed';
        exit;
    }
    $a = $cfg['assets'][$id];
    $size = (int) $a['size'];
    $mime = $a['m'];
    $etag = '"' . substr(hash('sha256', $id . '|' . $size . '|' . $cfg['site']), 0, 32) . '"';
    gvh_hdr('ETag', $etag);
    gvh_hdr('Accept-Ranges', 'bytes');
    gvh_hdr('X-Content-Type-Options', 'nosniff');
    gvh_hdr('X-Robots-Tag', 'noindex');
    gvh_hdr('Cache-Control', 'private, max-age=1800');
    gvh_hdr('Cross-Origin-Resource-Policy', 'same-origin');
    gvh_hdr('Referrer-Policy', 'same-origin');
    if (isset($_SERVER['HTTP_IF_NONE_MATCH']) && trim($_SERVER['HTTP_IF_NONE_MATCH']) === $etag) {
        gvh_status(304);
        exit;
    }
    $start = 0;
    $end = $size - 1;
    $partial = false;
    if (isset($_SERVER['HTTP_RANGE']) && preg_match('/bytes=(\d*)-(\d*)/', $_SERVER['HTTP_RANGE'], $m)) {
        $hasS = $m[1] !== '';
        $hasE = $m[2] !== '';
        if ($hasS) {
            $start = (int) $m[1];
            if ($hasE) {
                $end = (int) $m[2];
            }
        } else {
            $start = max(0, $size - (int) $m[2]);
            $end = $size - 1;
        }
        if ($hasS && $hasE && $end < $start) {
            gvh_status(416);
            gvh_hdr('Content-Range', 'bytes */' . $size);
            exit;
        }
        if ($end >= $size) {
            $end = $size - 1;
        }
        if ($start > $end || $start >= $size) {
            gvh_status(416);
            gvh_hdr('Content-Range', 'bytes */' . $size);
            exit;
        }
        $partial = true;
    }
    $len = $end - $start + 1;
    $bytes = gvh_asset_bytes($cfg, $a, $start, $len);
    if ($bytes === false) {
        gvh_status(500);
        exit;
    }
    $textual = (strpos($mime, 'text/') === 0 || $mime === 'application/javascript' || $mime === 'application/json' || $mime === 'image/svg+xml');
    gvh_hdr('Content-Type', $mime . ($textual ? '; charset=utf-8' : ''));
    if ($partial) {
        gvh_status(206);
        gvh_hdr('Content-Range', 'bytes ' . $start . '-' . $end . '/' . $size);
    } else {
        gvh_status(200);
    }
    gvh_hdr('Content-Length', (string) strlen($bytes));
    if (isset($_SERVER['REQUEST_METHOD']) && $_SERVER['REQUEST_METHOD'] === 'HEAD') {
        exit;
    }
    if (isset($_SERVER['REQUEST_METHOD']) && $_SERVER['REQUEST_METHOD'] === 'GET') {
        echo $bytes;
    }
    exit;
}

