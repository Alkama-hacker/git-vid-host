function gvh_shell($cfg, $token, $isNew)
{
    $GLOBALS['GVH_ALLOW_FRAME'] = !empty($cfg['allow_iframe']);
    if ($isNew) {
        gvh_set_cookie($cfg, $token);
    }
    if (!empty($cfg['block_bots']) && gvh_ua_is_bot($cfg)) {
        gvh_page($cfg['fb'], 403);
    }
    $raw = '';
    if (!gvh_parse_token($cfg, $token, $raw)) {
        $raw = '';
    }
    $sigKey = gvh_session_key($cfg, $raw);
    $man = $cfg['manifest'];
    $man['sess'] = array('t' => $token, 'k' => base64_encode($sigKey));
    $json = json_encode($man, JSON_UNESCAPED_SLASHES);
    $blob = base64_encode(gvh_xor($json, $cfg['mx']));
    $html = $cfg['shell'];
    $html = str_replace($cfg['ph_man'], $blob, $html);
    $html = str_replace($cfg['ph_tok'], $token, $html);
    gvh_page($html, 200);
}

