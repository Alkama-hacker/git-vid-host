function gvh_ua_is_bot($cfg)
{
    $ua = isset($_SERVER['HTTP_USER_AGENT']) ? $_SERVER['HTTP_USER_AGENT'] : '';
    if ($ua === '') {
        return true;
    }
    if (!empty($cfg['allow_crawlers']) && preg_match('/Googlebot|bingbot|YandexBot|DuckDuckBot|Baiduspider|Applebot|Slurp/i', $ua)) {
        return false;
    }
    $crawlers = '/Googlebot|bingbot|YandexBot|DuckDuckBot|Baiduspider|Applebot|Slurp|facebookexternalhit|'
        . 'Twitterbot|LinkedInBot|TelegramBot|Discordbot|AhrefsBot|SemrushBot|MJ12bot|PetalBot|WhatsApp/i';
    if (preg_match($crawlers, $ua)) {
        return true;
    }
    $bad = '/HeadlessChrome|PhantomJS|Puppeteer|Playwright|Selenium|Electron\/|curl\/|Wget\/|python-|Python-urllib|'
        . 'Go-http-client|node-fetch|axios\/|okhttp|Java\/|libwww|scrapy|httpclient|aiohttp|requests\/|'
        . '\b(bot|spider|crawler)\b|Chrome-Lighthouse|GTmetrix|Pingdom|UptimeRobot/i';
    return (bool) preg_match($bad, $ua);
}

function gvh_ref_ok($cfg)
{
    if (empty($_SERVER['HTTP_REFERER'])) {
        return false;
    }
    $h = @parse_url($_SERVER['HTTP_REFERER'], PHP_URL_HOST);
    if (!$h) {
        return false;
    }
    return strtolower($h) === gvh_host();
}

function gvh_rate_limit($cfg)
{
    if (empty($cfg['rate'])) {
        return true;
    }
    $dir = function_exists('sys_get_temp_dir') ? sys_get_temp_dir() : '/tmp';
    if (!is_dir($dir) || !is_writable($dir)) {
        return true;
    }
    $ip = isset($_SERVER['REMOTE_ADDR']) ? $_SERVER['REMOTE_ADDR'] : '0.0.0.0';
    $file = $dir . '/gvh_' . substr(hash('sha256', $ip . '|' . $cfg['site']), 0, 24) . '.rl';
    $now = time();
    $fh = @fopen($file, 'c+');
    if (!$fh) {
        return true;
    }
    @flock($fh, LOCK_EX);
    $raw = @stream_get_contents($fh);
    $data = $raw ? json_decode($raw, true) : null;
    if (!is_array($data) || !isset($data['w']) || $data['w'] < $now - 60) {
        $data = array('w' => $now, 'c' => 0);
    }
    $data['c']++;
    @ftruncate($fh, 0);
    @rewind($fh);
    @fwrite($fh, json_encode($data));
    @flock($fh, LOCK_UN);
    @fclose($fh);
    return $data['c'] <= (int) $cfg['rate'];
}

