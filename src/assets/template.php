function gvh_seal($sigKey, $api, $nonce, $payload)
{
    $stream = hash('sha256', $sigKey . '|' . $api . '|' . $nonce . '|r', true);
    $data = json_encode($payload, JSON_UNESCAPED_SLASHES);
    $out = '';
    $n = strlen($data);
    for ($i = 0; $i < $n; $i++) {
        $out .= chr(ord($data[$i]) ^ ord($stream[$i % 32]));
    }
    return base64_encode($out);
}

function gvh_api($cfg, $token)
{
    $api = (isset($_GET[$cfg['gw']]) && is_string($_GET[$cfg['gw']])) ? strtolower($_GET[$cfg['gw']]) : '';
    gvh_hdr('Content-Type', 'application/json; charset=utf-8');
    gvh_hdr('Cache-Control', 'no-store, no-cache, must-revalidate, max-age=0');
    gvh_hdr('Pragma', 'no-cache');
    gvh_hdr('X-Robots-Tag', 'noindex');
    gvh_hdr('X-Content-Type-Options', 'nosniff');
    if (!preg_match('/^[a-f0-9]{12,80}$/', $api)) {
        gvh_status(404);
        echo '{"e":1}';
        exit;
    }
    $raw = '';
    if ($token === '' || !gvh_parse_token($cfg, $token, $raw)) {
        gvh_status(403);
        echo '{"e":2}';
        exit;
    }
    if (!gvh_rate_limit($cfg)) {
        gvh_status(429);
        echo '{"e":3}';
        exit;
    }
    $nonce = (isset($_GET[$cfg['pn']]) && is_string($_GET[$cfg['pn']])) ? strtolower($_GET[$cfg['pn']]) : '';
    $sig = (isset($_GET[$cfg['ps']]) && is_string($_GET[$cfg['ps']])) ? strtolower($_GET[$cfg['ps']]) : '';
    if (!preg_match('/^[a-f0-9]{8,80}$/', $nonce) || !preg_match('/^[a-f0-9]{64}$/', $sig)) {
        gvh_status(403);
        echo '{"e":4}';
        exit;
    }
    $k = gvh_session_key($cfg, $raw);
    $want = hash_hmac('sha256', $api . '|' . $nonce, $k);
    if (!hash_equals($want, $sig)) {
        gvh_status(403);
        echo '{"e":5}';
        exit;
    }
    if (isset($cfg['api'][$api])) {
        $rec = $cfg['api'][$api];
    } else {
        // unknown name -> plausible decoy so blind probing yields nothing useful
        $seed = hash('sha256', $api . '|' . $cfg['site'], true);
        $alphabet = 'ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz23456789!#$%&()*+-./:;<=>?@[]^_{|}~';
        $decoyKey = '';
        for ($i = 0; $i < 50; $i++) {
            $decoyKey .= $alphabet[ord($seed[$i % 32]) % strlen($alphabet)];
        }
        $rec = array(
            'n' => -1,
            'k' => base64_encode($decoyKey),
            'iv' => base64_encode(substr($seed, 0, 12)),
            'ct' => base64_encode(random_bytes(48)),
            'tg' => base64_encode(random_bytes(16)),
        );
    }
    $out = array(
        'n' => isset($rec['n']) ? (int) $rec['n'] : -1,
        'k' => isset($rec['k']) ? $rec['k'] : base64_encode(''),
        'iv' => isset($rec['iv']) ? $rec['iv'] : base64_encode(''),
        'ct' => isset($rec['ct']) ? $rec['ct'] : '',
        'tg' => isset($rec['tg']) ? $rec['tg'] : '',
    );
    gvh_status(200);
    echo '{"p":"' . gvh_seal($k, $api, $nonce, $out) . '"}';
    exit;
}

